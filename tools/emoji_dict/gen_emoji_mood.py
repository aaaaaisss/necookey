#!/usr/bin/env python3
"""Generate app/src/main/assets/emoji/emoji_mood.tsv: ~150 popular chat emoji with one Japanese keyword
each (emoji <TAB> keyword <TAB> mood group), used by the after-commit context emoji (zenz PMI scoring).

Selection: sen-ltd/emoji-search-jp's 107 curated emoji + the most frequent emoji of the Unicode 2019
frequency ranking (freq2019.txt, https://home.unicode.org/emoji/emoji-frequency/) until TARGET.
Order = frequency rank (curated-only emoji after). Keyword: first unused emoji-search-jp tag (a
hiragana tag directly followed by a kanji tag is swapped, e.g. わらう/笑う -> 笑う), else CLDR ja keyword,
else CLDR tts; OVERRIDE fixes a few. Group = emoji-test.txt subgroup (prefiltering rotates over groups).

Usage: python3 gen_emoji_mood.py WORK OUT   (WORK has ja.xml, emoji-test.txt, data.json)
"""
import json, re, sys, html
from pathlib import Path

W = Path(sys.argv[1]); OUT = Path(sys.argv[2])
HERE = Path(__file__).parent
TARGET = 150
SKIP_GROUPS = {"country-flag", "subdivision-flag", "arrow", "keycap", "av-symbol", "geometric"}
SKIP = {"🖕"}
# hand fixes where the automatic pick is a poor chat keyword (CLDR descriptions, collisions)
OVERRIDE = {"✨": "キラキラ", "💖": "大好き", "🖤": "黒", "👀": "見る", "💓": "ときめき", "🙈": "見ざる",
            "🎶": "音楽", "‼️": "！！", "❣️": "ラブ", "♥️": "愛してる", "😇": "天使", "🔥": "燃える",
            "😅": "苦笑い", "💕": "ラブラブ", "🙋": "はーい", "💃": "ダンス", "👇": "下", "👉": "こちら"}
norm = lambda s: s.replace("\ufe0f", "")

fq, sub = {}, {}
cur = None
for line in (W / "emoji-test.txt").read_text(encoding="utf-8").splitlines():
    if line.startswith("# subgroup:"):
        cur = line.split(":", 1)[1].strip(); continue
    if "; fully-qualified" not in line or line.startswith("#"):
        continue
    s = "".join(chr(int(c, 16)) for c in line.split(";")[0].split())
    fq.setdefault(norm(s), s); sub.setdefault(norm(s), cur)

kw, tts = {}, {}
for m in re.finditer(r'<annotation cp="([^"]+)"( type="tts")?>([^<]*)</annotation>',
                     (W / "ja.xml").read_text(encoding="utf-8")):
    k = norm(html.unescape(m.group(1))); v = html.unescape(m.group(3))
    (tts if m.group(2) else kw)[k] = [x.strip() for x in v.split("|") if x.strip()]

sen = {norm(e["char"]): e["tags"] for e in json.load(open(W / "data.json", encoding="utf-8"))["emojis"]}
freq = [norm(t) for line in (HERE / "freq2019.txt").read_text(encoding="utf-8").splitlines()
        if not line.startswith("#") for t in line.split()]

def ok(k):
    return k in fq and k not in {norm(x) for x in SKIP} and sub[k] not in SKIP_GROUPS

chosen = [k for k in freq if k in sen and ok(k)]
for k in freq:
    if len(set(chosen) | set(sen)) >= TARGET: break
    if ok(k) and k not in chosen: chosen.append(k)
chosen += [k for k in sen if ok(k) and k not in chosen]

HIRA = re.compile(r"^[\u3041-\u309f]+$"); KANJI = re.compile(r"[\u4e00-\u9fff]")
JA = re.compile(r"^[^\x00-\x7f]{1,8}$")
used, rows = set(), []
for k in chosen:
    tags = list(sen.get(k, []))
    for i in range(len(tags) - 1):
        if HIRA.match(tags[i]) and KANJI.search(tags[i + 1]):
            tags[i], tags[i + 1] = tags[i + 1], tags[i]
    cands = [t for t in tags + kw.get(k, []) + tts.get(k, []) if JA.match(t) and t != "顔"]
    pick = OVERRIDE.get(fq[k]) or next((t for t in cands if t not in used and t not in OVERRIDE.values()), None)
    if pick is None: continue
    used.add(pick)
    rows.append(f"{fq[k]}\t{pick}\t{sub[k]}")
OUT.write_text("# emoji\tkeyword\tgroup  (generated by tools/emoji_dict/gen_emoji_mood.py)\n" + "\n".join(rows) + "\n", encoding="utf-8")
print(len(rows), "emoji,", len({r.split('\t')[2] for r in rows}), "groups")
